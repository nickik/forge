    writeln!(out, "    list.block = memory_block_none();").unwrap();
    writeln!(out, "    list.len = 0;").unwrap();
    writeln!(out, "    list.capacity = 0;").unwrap();
    writeln!(out, "    return result_void_ok();").unwrap();
    writeln!(out, "}}\n").unwrap();
