use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

#[derive(Clone, Copy)]
struct TypeSpec {
    forge: &'static str,
    suffix: &'static str,
    size: usize,
    align: usize,
}

#[derive(Clone, Copy)]
struct MapSpec {
    key: TypeSpec,
    value: TypeSpec,
}

const U8: TypeSpec = TypeSpec { forge: "u8", suffix: "U8", size: 1, align: 1 };
const U64: TypeSpec = TypeSpec { forge: "u64", suffix: "U64", size: 8, align: 8 };
const USIZE: TypeSpec = TypeSpec { forge: "usize", suffix: "Usize", size: 8, align: 8 };
const STRING: TypeSpec = TypeSpec { forge: "str", suffix: "String", size: 16, align: 8 };

const LISTS: &[TypeSpec] = &[U8, U64, USIZE, STRING];
const SETS: &[TypeSpec] = &[U64, STRING];
const MAPS: &[MapSpec] = &[
    MapSpec { key: STRING, value: STRING },
    MapSpec { key: STRING, value: USIZE },
    MapSpec { key: STRING, value: U64 },
    MapSpec { key: U64, value: U64 },
];

fn snake(suffix: &str) -> String {
    let mut out = String::new();
    for (index, ch) in suffix.chars().enumerate() {
        if ch.is_ascii_uppercase() && index != 0 {
            out.push('_');
        }
        out.push(ch.to_ascii_lowercase());
    }
    out
}

fn emit_header(out: &mut String) {
    writeln!(out, "// @generated by forge-collections-gen. DO NOT EDIT BY HAND.").unwrap();
    writeln!(out, "// Type-specialized collections intended for the compiled Forge backend.").unwrap();
    writeln!(out, "//").unwrap();
    writeln!(out, "// Allocation rule: collection values NEVER retain an Allocator capability.").unwrap();
    writeln!(out, "// Every operation that may allocate, reallocate, or free receives the allocator").unwrap();
    writeln!(out, "// explicitly at the call site. Non-allocating operations do not receive one.").unwrap();
    writeln!(out, "module forge_collections_native;\n").unwrap();
    writeln!(out, "import core;").unwrap();
    writeln!(out, "import core.hash;").unwrap();
    writeln!(out, "import std.string;\n").unwrap();

    writeln!(out, "// Native boundary: typed access to allocator-owned MemoryBlock storage.").unwrap();
    writeln!(out, "// Collection policy stays in generated Forge code; these are raw storage operations.").unwrap();
    writeln!(out, "nfn storage_load_u8(block: &core.MemoryBlock, index: usize) -> u8 {{ }}").unwrap();
    writeln!(out, "nfn storage_store_u8(block: &mut core.MemoryBlock, index: usize, value: u8) -> void {{ }}").unwrap();
    writeln!(out, "nfn storage_load_u64(block: &core.MemoryBlock, index: usize) -> u64 {{ }}").unwrap();
    writeln!(out, "nfn storage_store_u64(block: &mut core.MemoryBlock, index: usize, value: u64) -> void {{ }}").unwrap();
    writeln!(out, "nfn storage_load_usize(block: &core.MemoryBlock, index: usize) -> usize {{ }}").unwrap();
    writeln!(out, "nfn storage_store_usize(block: &mut core.MemoryBlock, index: usize, value: usize) -> void {{ }}").unwrap();
    writeln!(out, "nfn storage_load_string(block: &core.MemoryBlock, index: usize) -> str {{ }}").unwrap();
    writeln!(out, "nfn storage_store_string(block: &mut core.MemoryBlock, index: usize, value: str) -> void {{ }}\n").unwrap();

    writeln!(out, "pub const COLLECTION_INITIAL_CAPACITY: usize = 8;").unwrap();
    writeln!(out, "pub const COLLECTION_LOAD_NUMERATOR: usize = 7;").unwrap();
    writeln!(out, "pub const COLLECTION_LOAD_DENOMINATOR: usize = 10;\n").unwrap();

    writeln!(out, "pub fn next_capacity(current: usize, requested: usize) -> usize {{").unwrap();
    writeln!(out, "    var next: usize = current;").unwrap();
    writeln!(out, "    if (next == 0) {{ next = 4; }}").unwrap();
    writeln!(out, "    while (next < requested) {{ next = next * 2; }}").unwrap();
    writeln!(out, "    return next;").unwrap();
    writeln!(out, "}}\n").unwrap();

    writeln!(out, "pub fn hash_u64(value: u64) -> u64 {{ return core.hash.hash_u64(value); }}").unwrap();
    writeln!(out, "pub fn hash_usize(value: usize) -> u64 {{ return core.hash.hash_usize(value); }}").unwrap();
    writeln!(out, "pub fn hash_string(value: str) -> u64 {{").unwrap();
    writeln!(out, "    var state: u64 = core.hash.hash_init_u64();").unwrap();
    writeln!(out, "    var index: usize = 0;").unwrap();
    writeln!(out, "    val count: usize = string.byte_len(value);").unwrap();
    writeln!(out, "    while (index < count) {{").unwrap();
    writeln!(out, "        state = core.hash.hash_octet_u64(state, u64(string.byte_at(value, index)));").unwrap();
    writeln!(out, "        index = index + 1;").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    return core.hash.hash_finish_u64(state);").unwrap();
    writeln!(out, "}}\n").unwrap();

    writeln!(out, "pub fn eq_u64(a: u64, b: u64) -> bool {{ return a == b; }}").unwrap();
    writeln!(out, "pub fn eq_usize(a: usize, b: usize) -> bool {{ return a == b; }}").unwrap();
    writeln!(out, "pub fn eq_string(a: str, b: str) -> bool {{ return a == b; }}\n").unwrap();
}

fn emit_list(out: &mut String, ty: TypeSpec) {
    let name = snake(ty.suffix);
    writeln!(out, "// List{}: contiguous growable vector.", ty.suffix).unwrap();
    writeln!(out, "// element_size={} element_align={}", ty.size, ty.align).unwrap();
    writeln!(out, "pub struct List{} {{", ty.suffix).unwrap();
    writeln!(out, "    block: core.MemoryBlock?;").unwrap();
    writeln!(out, "    len: usize;").unwrap();
    writeln!(out, "    capacity: usize;").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out, "nfn list_{name}_create() -> List{} {{ }}", ty.suffix).unwrap();
    writeln!(out, "nfn list_{name}_with_capacity(allocator: &mut core.Allocator, capacity: usize) -> Result[List{}, core.AllocError] {{ }}", ty.suffix).unwrap();
    writeln!(out, "pub fn list_{name}_len(list: &List{}) -> usize {{ return list.len; }}", ty.suffix).unwrap();
    writeln!(out, "pub fn list_{name}_capacity(list: &List{}) -> usize {{ return list.capacity; }}", ty.suffix).unwrap();
    writeln!(out, "pub fn list_{name}_is_empty(list: &List{}) -> bool {{ return list.len == 0; }}", ty.suffix).unwrap();
    writeln!(out, "nfn list_{name}_try_reserve(list: &mut List{}, allocator: &mut core.Allocator, capacity: usize) -> Result[void, core.AllocError] {{ }}", ty.suffix).unwrap();
    writeln!(out, "nfn list_{name}_push(list: &mut List{}, allocator: &mut core.Allocator, value: {}) -> Result[void, core.AllocError] {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn list_{name}_insert(list: &mut List{}, allocator: &mut core.Allocator, index: usize, value: {}) -> Result[void, core.AllocError] {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn list_{name}_pop(list: &mut List{}) -> {}? {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn list_{name}_get(list: &List{}, index: usize) -> {} {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn list_{name}_set(list: &mut List{}, index: usize, value: {}) -> void {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn list_{name}_remove(list: &mut List{}, index: usize) -> {} {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn list_{name}_swap_remove(list: &mut List{}, index: usize) -> {} {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn list_{name}_clear(list: &mut List{}) -> void {{ }}", ty.suffix).unwrap();
    writeln!(out, "nfn list_{name}_truncate(list: &mut List{}, len: usize) -> void {{ }}", ty.suffix).unwrap();
    writeln!(out, "nfn list_{name}_destroy(list: &mut List{}, allocator: &mut core.Allocator) -> void {{ }}\n", ty.suffix).unwrap();
}

fn emit_set(out: &mut String, ty: TypeSpec) {
    let name = snake(ty.suffix);
    writeln!(out, "// HashSet{}: open addressing, linear probing, tombstones.", ty.suffix).unwrap();
    writeln!(out, "pub struct HashSet{} {{", ty.suffix).unwrap();
    writeln!(out, "    states: core.MemoryBlock?;").unwrap();
    writeln!(out, "    keys: core.MemoryBlock?;").unwrap();
    writeln!(out, "    len: usize;").unwrap();
    writeln!(out, "    buckets: usize;").unwrap();
    writeln!(out, "    tombstones: usize;").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out, "nfn hash_set_{name}_create() -> HashSet{} {{ }}", ty.suffix).unwrap();
    writeln!(out, "nfn hash_set_{name}_contains(set: &HashSet{}, value: {}) -> bool {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn hash_set_{name}_insert(set: &mut HashSet{}, allocator: &mut core.Allocator, value: {}) -> Result[bool, core.AllocError] {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn hash_set_{name}_remove(set: &mut HashSet{}, value: {}) -> bool {{ }}", ty.suffix, ty.forge).unwrap();
    writeln!(out, "nfn hash_set_{name}_try_reserve(set: &mut HashSet{}, allocator: &mut core.Allocator, capacity: usize) -> Result[void, core.AllocError] {{ }}", ty.suffix).unwrap();
    writeln!(out, "nfn hash_set_{name}_clear(set: &mut HashSet{}) -> void {{ }}", ty.suffix).unwrap();
    writeln!(out, "nfn hash_set_{name}_destroy(set: &mut HashSet{}, allocator: &mut core.Allocator) -> void {{ }}\n", ty.suffix).unwrap();
}

fn emit_map(out: &mut String, spec: MapSpec) {
    let key_name = snake(spec.key.suffix);
    let value_name = snake(spec.value.suffix);
    let suffix = format!("{}{}", spec.key.suffix, spec.value.suffix);
    writeln!(out, "// HashMap{suffix}: shared open-addressing table algorithm.").unwrap();
    writeln!(out, "pub struct HashMap{suffix} {{").unwrap();
    writeln!(out, "    states: core.MemoryBlock?;").unwrap();
    writeln!(out, "    keys: core.MemoryBlock?;").unwrap();
    writeln!(out, "    values: core.MemoryBlock?;").unwrap();
    writeln!(out, "    len: usize;").unwrap();
    writeln!(out, "    buckets: usize;").unwrap();
    writeln!(out, "    tombstones: usize;").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out, "nfn hash_map_{key_name}_{value_name}_create() -> HashMap{suffix} {{ }}").unwrap();
    writeln!(out, "nfn hash_map_{key_name}_{value_name}_contains(map: &HashMap{suffix}, key: {}) -> bool {{ }}", spec.key.forge).unwrap();
    writeln!(out, "nfn hash_map_{key_name}_{value_name}_get(map: &HashMap{suffix}, key: {}) -> {}? {{ }}", spec.key.forge, spec.value.forge).unwrap();
    writeln!(out, "nfn hash_map_{key_name}_{value_name}_put(map: &mut HashMap{suffix}, allocator: &mut core.Allocator, key: {}, value: {}) -> Result[bool, core.AllocError] {{ }}", spec.key.forge, spec.value.forge).unwrap();
    writeln!(out, "nfn hash_map_{key_name}_{value_name}_remove(map: &mut HashMap{suffix}, key: {}) -> bool {{ }}", spec.key.forge).unwrap();
    writeln!(out, "nfn hash_map_{key_name}_{value_name}_try_reserve(map: &mut HashMap{suffix}, allocator: &mut core.Allocator, capacity: usize) -> Result[void, core.AllocError] {{ }}").unwrap();
    writeln!(out, "nfn hash_map_{key_name}_{value_name}_clear(map: &mut HashMap{suffix}) -> void {{ }}").unwrap();
    writeln!(out, "nfn hash_map_{key_name}_{value_name}_destroy(map: &mut HashMap{suffix}, allocator: &mut core.Allocator) -> void {{ }}\n").unwrap();
}

fn generate() -> String {
    let mut out = String::new();
    emit_header(&mut out);
    for ty in LISTS {
        emit_list(&mut out, *ty);
    }
    for ty in SETS {
        emit_set(&mut out, *ty);
    }
    for spec in MAPS {
        emit_map(&mut out, *spec);
    }
    out
}

fn main() {
    let mut args = env::args().skip(1);
    let output = args
        .next()
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("packages/forge-collections-native/src/lib.fg"));
    if args.next().is_some() {
        eprintln!("usage: forge-collections-gen [OUTPUT]");
        std::process::exit(2);
    }

    let source = generate();
    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent).expect("create output directory");
    }
    fs::write(&output, source).expect("write generated collections");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_collections_do_not_store_allocator_capabilities() {
        let source = generate();
        assert!(!source.contains("allocator: &mut core.Allocator;"));
        assert!(source.contains("list_u8_push(list: &mut ListU8, allocator: &mut core.Allocator"));
        assert!(source.contains("hash_map_u64_u64_put(map: &mut HashMapU64U64, allocator: &mut core.Allocator"));
    }

    #[test]
    fn requested_specializations_are_generated() {
        let source = generate();
        for name in [
            "ListU8",
            "ListU64",
            "ListUsize",
            "ListString",
            "HashSetU64",
            "HashSetString",
            "HashMapStringString",
            "HashMapStringUsize",
            "HashMapStringU64",
            "HashMapU64U64",
        ] {
            assert!(source.contains(name), "missing {name}");
        }
    }
}
