use std::env;
use std::fs;
use std::path::PathBuf;

#[derive(Clone, Copy)]
struct TypeSpec {
    forge: &'static str,
    suffix: &'static str,
    size: usize,
    align: usize,
    hash: &'static str,
    eq: &'static str,
}

#[derive(Clone, Copy)]
struct MapSpec {
    key: TypeSpec,
    value: TypeSpec,
}

const U8: TypeSpec = TypeSpec {
    forge: "u8",
    suffix: "U8",
    size: 1,
    align: 1,
    hash: "hash_u8",
    eq: "eq_u8",
};
const U64: TypeSpec = TypeSpec {
    forge: "u64",
    suffix: "U64",
    size: 8,
    align: 8,
    hash: "hash_u64",
    eq: "eq_u64",
};
const USIZE: TypeSpec = TypeSpec {
    forge: "usize",
    suffix: "Usize",
    size: 8,
    align: 8,
    hash: "hash_usize",
    eq: "eq_usize",
};
const STRING: TypeSpec = TypeSpec {
    forge: "str",
    suffix: "String",
    size: 16,
    align: 8,
    hash: "hash_string",
    eq: "eq_string",
};

const LISTS: &[TypeSpec] = &[U8, U64, USIZE, STRING];
const SETS: &[TypeSpec] = &[U64, STRING];
const MAPS: &[MapSpec] = &[
    MapSpec { key: STRING, value: STRING },
    MapSpec { key: STRING, value: USIZE },
    MapSpec { key: STRING, value: U64 },
    MapSpec { key: U64, value: U64 },
];

fn snake(suffix: &str) -> String {
    let mut out = String::new();
    for (i, c) in suffix.chars().enumerate() {
        if c.is_ascii_uppercase() && i != 0 {
            out.push('_');
        }
        out.push(c.to_ascii_lowercase());
    }
    out
}

fn emit_header(out: &mut String) {
    out.push_str("// @generated by forge-collections-gen. DO NOT EDIT BY HAND.\n");
    out.push_str("// The generated API is type-specialized; no language generics are required.\n\n");
    out.push_str("module forge_collections_native;\n\n");
    out.push_str("import core;\nimport core.hash;\nimport std.string;\n\n");
    out.push_str("// Backend memory intrinsics operate on allocator-owned MemoryBlock storage.\n");
    out.push_str("// The compiled backend lowers these directly to typed loads/stores. They are\n");
    out.push_str("// not collection implementations and must not allocate on their own.\n");
    out.push_str("nfn storage_load_u8(block: &core.MemoryBlock, index: usize) -> u8 { }\n");
    out.push_str("nfn storage_store_u8(block: &mut core.MemoryBlock, index: usize, value: u8) -> void { }\n");
    out.push_str("nfn storage_load_u64(block: &core.MemoryBlock, index: usize) -> u64 { }\n");
    out.push_str("nfn storage_store_u64(block: &mut core.MemoryBlock, index: usize, value: u64) -> void { }\n");
    out.push_str("nfn storage_load_usize(block: &core.MemoryBlock, index: usize) -> usize { }\n");
    out.push_str("nfn storage_store_usize(block: &mut core.MemoryBlock, index: usize, value: usize) -> void { }\n");
    out.push_str("nfn storage_load_string(block: &core.MemoryBlock, index: usize) -> str { }\n");
    out.push_str("nfn storage_store_string(block: &mut core.MemoryBlock, index: usize, value: str) -> void { }\n\n");
    out.push_str("pub const COLLECTION_INITIAL_CAPACITY: usize = 8;\n");
    out.push_str("pub const COLLECTION_LOAD_NUMERATOR: usize = 7;\n");
    out.push_str("pub const COLLECTION_LOAD_DENOMINATOR: usize = 10;\n\n");
    out.push_str("pub fn next_capacity(current: usize, requested: usize) -> usize {\n");
    out.push_str("    var next: usize = current;\n    if (next == 0) { next = 4; }\n");
    out.push_str("    while (next < requested) { next = next * 2; }\n    return next;\n}\n\n");
    out.push_str("pub fn hash_u64(value: u64) -> u64 { return core.hash.hash_u64(value); }\n");
    out.push_str("pub fn hash_usize(value: usize) -> usize { return core.hash.hash_usize(value); }\n");
    out.push_str("pub fn hash_string(value: str) -> usize {\n");
    out.push_str("    var state: usize = core.hash.hash_init_usize();\n    var i: usize = 0;\n");
    out.push_str("    val count: usize = string.byte_len(value);\n    while (i < count) {\n");
    out.push_str("        state = core.hash.hash_octet_usize(state, string.byte_at(value, i));\n        i = i + 1;\n    }\n");
    out.push_str("    return core.hash.hash_finish_usize(state);\n}\n\n");
    out.push_str("pub fn eq_u64(a: u64, b: u64) -> bool { return a == b; }\n");
    out.push_str("pub fn eq_usize(a: usize, b: usize) -> bool { return a == b; }\n");
    out.push_str("pub fn eq_string(a: str, b: str) -> bool { return a == b; }\n\n");
}

fn emit_list(out: &mut String, ty: TypeSpec) {
    let n = snake(ty.suffix);
    out.push_str(&format!("// List{}: contiguous allocator-owned growable vector.\n", ty.suffix));
    out.push_str(&format!("pub struct List{} {{\n", ty.suffix));
    out.push_str("    allocator: &mut core.Allocator;\n    block: core.MemoryBlock;\n    len: usize;\n    capacity: usize;\n}\n");
    out.push_str(&format!("pub fn list_{n}_len(list: &List{}) -> usize {{ return list.len; }}\n", ty.suffix));
    out.push_str(&format!("pub fn list_{n}_capacity(list: &List{}) -> usize {{ return list.capacity; }}\n", ty.suffix));
    out.push_str(&format!("pub fn list_{n}_is_empty(list: &List{}) -> bool {{ return list.len == 0; }}\n", ty.suffix));
    out.push_str(&format!("// element_size={} element_align={}\n", ty.size, ty.align));
    out.push_str(&format!("// Generated operations: with_capacity, try_reserve, push, pop, get, set, insert, remove, swap_remove, clear, truncate, destroy.\n"));
    out.push_str(&format!("nfn list_{n}_with_capacity(allocator: &mut core.Allocator, capacity: usize) -> Result[List{}, core.AllocError] {{ }}\n", ty.suffix));
    out.push_str(&format!("nfn list_{n}_try_reserve(list: &mut List{}, capacity: usize) -> Result[void, core.AllocError] {{ }}\n", ty.suffix));
    out.push_str(&format!("nfn list_{n}_push(list: &mut List{}, value: {}) -> Result[void, core.AllocError] {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn list_{n}_pop(list: &mut List{}) -> {}? {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn list_{n}_get(list: &List{}, index: usize) -> {} {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn list_{n}_set(list: &mut List{}, index: usize, value: {}) -> void {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn list_{n}_insert(list: &mut List{}, index: usize, value: {}) -> Result[void, core.AllocError] {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn list_{n}_remove(list: &mut List{}, index: usize) -> {} {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn list_{n}_swap_remove(list: &mut List{}, index: usize) -> {} {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn list_{n}_clear(list: &mut List{}) -> void {{ }}\n", ty.suffix));
    out.push_str(&format!("nfn list_{n}_truncate(list: &mut List{}, len: usize) -> void {{ }}\n", ty.suffix));
    out.push_str(&format!("nfn list_{n}_destroy(list: &mut List{}) -> void {{ }}\n\n", ty.suffix));
}

fn emit_set(out: &mut String, ty: TypeSpec) {
    let n = snake(ty.suffix);
    out.push_str(&format!("// HashSet{} uses open addressing, linear probing and tombstones.\n", ty.suffix));
    out.push_str(&format!("pub struct HashSet{} {{\n", ty.suffix));
    out.push_str("    allocator: &mut core.Allocator;\n    states: core.MemoryBlock;\n    keys: core.MemoryBlock;\n    len: usize;\n    buckets: usize;\n    tombstones: usize;\n}\n");
    out.push_str(&format!("// hash={} equality={} key_size={} key_align={}\n", ty.hash, ty.eq, ty.size, ty.align));
    out.push_str(&format!("nfn hash_set_{n}_create(allocator: &mut core.Allocator) -> Result[HashSet{}, core.AllocError] {{ }}\n", ty.suffix));
    out.push_str(&format!("nfn hash_set_{n}_contains(set: &HashSet{}, value: {}) -> bool {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn hash_set_{n}_insert(set: &mut HashSet{}, value: {}) -> Result[bool, core.AllocError] {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn hash_set_{n}_remove(set: &mut HashSet{}, value: {}) -> bool {{ }}\n", ty.suffix, ty.forge));
    out.push_str(&format!("nfn hash_set_{n}_try_reserve(set: &mut HashSet{}, capacity: usize) -> Result[void, core.AllocError] {{ }}\n", ty.suffix));
    out.push_str(&format!("nfn hash_set_{n}_clear(set: &mut HashSet{}) -> void {{ }}\n", ty.suffix));
    out.push_str(&format!("nfn hash_set_{n}_destroy(set: &mut HashSet{}) -> void {{ }}\n\n", ty.suffix));
}

fn emit_map(out: &mut String, spec: MapSpec) {
    let ks = snake(spec.key.suffix);
    let vs = snake(spec.value.suffix);
    let suffix = format!("{}{}", spec.key.suffix, spec.value.suffix);
    out.push_str(&format!("// HashMap{suffix}: shared open-addressing table algorithm.\n"));
    out.push_str(&format!("pub struct HashMap{suffix} {{\n"));
    out.push_str("    allocator: &mut core.Allocator;\n    states: core.MemoryBlock;\n    keys: core.MemoryBlock;\n    values: core.MemoryBlock;\n    len: usize;\n    buckets: usize;\n    tombstones: usize;\n}\n");
    out.push_str(&format!("// key_hash={} key_eq={} key_size={} value_size={}\n", spec.key.hash, spec.key.eq, spec.key.size, spec.value.size));
    out.push_str(&format!("nfn hash_map_{ks}_{vs}_create(allocator: &mut core.Allocator) -> Result[HashMap{suffix}, core.AllocError] {{ }}\n"));
    out.push_str(&format!("nfn hash_map_{ks}_{vs}_contains(map: &HashMap{suffix}, key: {}) -> bool {{ }}\n", spec.key.forge));
    out.push_str(&format!("nfn hash_map_{ks}_{vs}_get(map: &HashMap{suffix}, key: {}) -> {}? {{ }}\n", spec.key.forge, spec.value.forge));
    out.push_str(&format!("nfn hash_map_{ks}_{vs}_put(map: &mut HashMap{suffix}, key: {}, value: {}) -> Result[bool, core.AllocError] {{ }}\n", spec.key.forge, spec.value.forge));
    out.push_str(&format!("nfn hash_map_{ks}_{vs}_remove(map: &mut HashMap{suffix}, key: {}) -> bool {{ }}\n", spec.key.forge));
    out.push_str(&format!("nfn hash_map_{ks}_{vs}_try_reserve(map: &mut HashMap{suffix}, capacity: usize) -> Result[void, core.AllocError] {{ }}\n"));
    out.push_str(&format!("nfn hash_map_{ks}_{vs}_clear(map: &mut HashMap{suffix}) -> void {{ }}\n"));
    out.push_str(&format!("nfn hash_map_{ks}_{vs}_destroy(map: &mut HashMap{suffix}) -> void {{ }}\n\n"));
}

fn generate() -> String {
    let mut out = String::new();
    emit_header(&mut out);
    for ty in LISTS { emit_list(&mut out, *ty); }
    for ty in SETS { emit_set(&mut out, *ty); }
    for spec in MAPS { emit_map(&mut out, *spec); }
    out
}

fn main() {
    let mut args = env::args().skip(1);
    let output = args.next().map(PathBuf::from).unwrap_or_else(|| {
        PathBuf::from("packages/forge-collections-native/src/lib.fg")
    });
    if args.next().is_some() {
        eprintln!("usage: forge-collections-gen [OUTPUT]");
        std::process::exit(2);
    }
    let source = generate();
    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent).expect("create output directory");
    }
    fs::write(&output, source).expect("write generated Forge collections");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generation_is_deterministic() {
        assert_eq!(generate(), generate());
    }

    #[test]
    fn contains_required_specializations() {
        let source = generate();
        for name in [
            "ListU8", "ListU64", "ListUsize", "ListString",
            "HashSetU64", "HashSetString",
            "HashMapStringString", "HashMapStringUsize",
            "HashMapStringU64", "HashMapU64U64",
        ] {
            assert!(source.contains(name), "missing {name}");
        }
    }

    #[test]
    fn generated_collections_are_allocator_owned() {
        let source = generate();
        assert!(source.contains("allocator: &mut core.Allocator"));
        assert!(source.contains("core.MemoryBlock"));
        assert!(!source.contains("std.collections.raw_"));
    }
}
