use std::fs;
use std::path::PathBuf;

#[derive(Clone, Copy)]
struct TypeSpec {
    forge: &'static str,
    suffix: &'static str,
    size: usize,
    align: usize,
}

#[derive(Clone, Copy)]
struct MapSpec {
    key: TypeSpec,
    value: TypeSpec,
}

const U8: TypeSpec = TypeSpec {
    forge: "u8",
    suffix: "U8",
    size: 1,
    align: 1,
};
const U64: TypeSpec = TypeSpec {
    forge: "u64",
    suffix: "U64",
    size: 8,
    align: 8,
};
const USIZE: TypeSpec = TypeSpec {
    forge: "usize",
    suffix: "Usize",
    size: 8,
    align: 8,
};
const STRING: TypeSpec = TypeSpec {
    forge: "str",
    suffix: "String",
    size: 16,
    align: 8,
};

const LISTS: &[TypeSpec] = &[U8, USIZE, STRING];
const SETS: &[TypeSpec] = &[U64, STRING];
const MAPS: &[MapSpec] = &[
    MapSpec {
        key: STRING,
        value: STRING,
    },
    MapSpec {
        key: STRING,
        value: USIZE,
    },
    MapSpec {
        key: STRING,
        value: U64,
    },
    MapSpec {
        key: U64,
        value: U64,
    },
];

fn snake(suffix: &str) -> String {
    let mut out = String::new();
    for (index, ch) in suffix.chars().enumerate() {
        if ch.is_ascii_uppercase() && index != 0 {
            out.push('_');
        }
        out.push(ch.to_ascii_lowercase());
    }
    out
}

