    writeln!(out, "    len: usize;").unwrap();
    writeln!(out, "    capacity: usize;").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out, "nfn result_list_u64_ok(value: ListU64) -> Result[ListU64, core.AllocError] {{ }}").unwrap();
    writeln!(out, "pub fn list_u64_create() -> ListU64 {{").unwrap();
